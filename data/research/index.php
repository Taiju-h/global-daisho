      <h2>Timeline of High-Pressure Jet Mixing</h2>

      <dl id="a_1969">
        <dt>From 1969 <span>(Pioneer Era)</span> <strong>High-Pressure Jet Injection Method</strong></dt>
        <dd>
          <h3>Single-Pipe Method (e.g. CCP Method)</h3>
          <p>
            The single-pipe jet method was initially called the High-Pressure Jet Injection Method, developed to overcome the limitations of traditional chemical grouting.<br>
            Previously, chemical grouting had difficulties ensuring consistent penetration and stabilization effects due to varying soil conditions.<br>
            In 1969, a high-pressure pump was introduced into the equipment for chemical grouting, enabling grout to be injected and jetted at high pressure to cut and mix the ground, creating improved ground bodies.
          </p>
          <p>[ Applications ]<br>
            1. Increasing ground bearing capacity<br>
            2. Retaining walls or cut-off walls for excavation<br>
            3. Earth and water pressure resistance for shield tunneling launch/arrival zones<br>
            4. Reinforcement and stabilization during tunnel expansion<br>
            <span>At the time, the method was mainly used as temporary works due to limited quality reliability.</span>
          </p>
          <table border="0" cellspacing="0" cellpadding="0">
            <tr><th>Method Name</th><td>CCP Method (Single Pipe)</td></tr>
            <tr><th>Injection Mechanism</th><td>[Single Pipe] Grouting injected via a single pipe</td></tr>
            <tr><th>Improvement Diameter</th><td>500mm</td></tr>
            <tr><th>Applicable Ground</th><td>Soft ground</td></tr>
            <tr><th>Impact on Surrounding Ground</th><td>Yes</td></tr>
            <tr><th>Features</th><td>Mixing and filling</td></tr>
          </table>
        </dd>
      </dl>

      <dl id="a_1970">
        <dt>From 1970 <span>(Development Era)</span> <strong>High-Pressure Jet Mixing Method</strong></dt>
        <dd>
          <h3>Double-Pipe Method (e.g. JSG Method)</h3>
          <p>
            As single-pipe jetting became more common, demand grew for larger improvement diameters. To prevent pressure loss within the ground, a method was developed where grout and compressed air were injected simultaneously.<br>
            The double-pipe method consists of an inner pipe for grout injection and an outer pipe for compressed air discharge.<br>
            Improvement diameters range from 1,000 to 2,000mm.
          </p>
          <table border="0" cellspacing="0" cellpadding="0">
            <tr><th>Method Name</th><td>CJG Method (Triple Pipe)</td></tr>
            <tr><th>Injection Mechanism</th><td>[Triple Pipe] Water and compressed air jetting, followed by grout injection</td></tr>
            <tr><th>Improvement Diameter</th><td>2000mm</td></tr>
            <tr><th>Applicable Ground</th><td>Soft to normal ground</td></tr>
            <tr><th>Impact on Surrounding Ground</th><td>None</td></tr>
            <tr><th>Features</th><td>Mixing and filling</td></tr>
          </table>

          <h3>Triple-Pipe Method (e.g. RJP Method, CJG Method)</h3>
          <p>
            The double-pipe method tended to affect surrounding ground when injecting large amounts of grout. To solve this, water jetting was added to develop the triple-pipe high-pressure jet mixing method.<br>
            Improvement diameters range from 2,000 to 3,000mm.
          </p>
          <table border="0" cellspacing="0" cellpadding="0">
            <tr><th>Method Name</th><td>RJP Method (Triple Pipe)</td></tr>
            <tr><th>Injection Mechanism</th><td>[Triple Pipe] Water and compressed air jetting, followed by grout and compressed air</td></tr>
            <tr><th>Improvement Diameter</th><td>3500mm</td></tr>
            <tr><th>Applicable Ground</th><td>Soft to normal ground</td></tr>
            <tr><th>Impact on Surrounding Ground</th><td>None</td></tr>
            <tr><th>Features</th><td>Introduced swing mechanism, enabling fan-shaped improvements for the first time</td></tr>
          </table>
          <ul>
            <li>Founder Naka Haneda developed and supplied fluidizers for jet mixing methods</li>
            <li>Establishment of Daisho Chemical R&D</li>
          </ul>
        </dd>
      </dl>


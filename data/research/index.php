      <dl id="a_2009">
        <dt class="opt">From 2009 <span>(Recent)</span> <strong>OPT Jet Method</strong></dt>
        <dd>
          <h3 class="opt">Low Displacement, Low Waste Jet Mixing Method (OPT Jet Method)</h3>
          <h4>Large Diameter, High-Speed Construction<br>Versatile for both temporary and permanent works</h4>
          <p>[ Advanced Technology ]<br>Enables fast and economical construction through reduced waste and high-speed operation.<br>Efficient cutting achieved in a shorter time.</p>

          <p>[ Large Diameter ]<br>The OPT Jet Method controls injection speed, volume, time, and pressure to efficiently achieve the required improvement diameter. As a result, it has been expanding its market share in recent years.</p>

          <p>Meanwhile, the Super Jet Method and JEP Method have been developed for even larger diameters exceeding 5m.<br>Subsequently, a similar method, the V-Jet Method, emerged around 2011.</p>

          <p>[ Superior Applicability in Construction Environments ]<br>Jet mixing methods are advantageous for improving ground in areas with height restrictions, narrow spaces, or confined underground conditions. Equipment downsizing, smaller rod diameters, and high-performance jet devices have been developed to meet these demands.</p>

          <p>Permanent applications for seismic and durability purposes are also increasing due to improved quality and efficiency.</p>

